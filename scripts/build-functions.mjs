/**
 * Bundles each serverless entrypoint into a single file.
 *
 * HubSpot packages an app function as exactly one file: the entrypoint is
 * copied to /var/task/file.js and nothing else from the project goes with it —
 * a probe of the running function listed /var/task as file.js and HubSpot's
 * own handler, full stop. So `require("./lib/guard.js")` throws at load and
 * both endpoints answered 500 until this existed. Dependencies from
 * package.json are fine: axios resolves through NODE_PATH.
 *
 * Sources live in hubspot/functions-src, outside the project's srcDir, so the
 * uploaded tree carries only what runs. The output is committed, like the
 * theme stylesheet, and the deploy fails if it is stale.
 *
 *   node scripts/build-functions.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const SRC = "hubspot/functions-src";
const OUT = "hubspot/src/app/functions";
const ENTRIES = ["chat.js", "diagnose.js", "probe.js"];

/** Only our own files are inlined; node built-ins and axios stay requires. */
const LOCAL_REQUIRE = /require\(\s*["'](\.[^"']+)["']\s*\)/g;

/**
 * Walks the local require graph from an entrypoint.
 * Ids are paths relative to SRC, which is what the module map is keyed by.
 */
function collect(id, modules = new Map()) {
  if (modules.has(id)) return modules;
  const source = readFileSync(path.join(SRC, id), "utf8");
  modules.set(id, null); // claim the slot first: a cycle must not recurse
  const deps = [];
  const rewritten = source.replace(LOCAL_REQUIRE, (_, rel) => {
    const dep = path.posix.normalize(path.posix.join(path.posix.dirname(id), rel));
    deps.push(dep);
    return `__require(${JSON.stringify(dep)})`;
  });
  modules.set(id, rewritten);
  for (const dep of deps) collect(dep, modules);
  return modules;
}

/** A .json dependency is a module whose exports are the parsed document. */
function wrap(id, source) {
  const body = id.endsWith(".json")
    ? `module.exports = ${source.trim()};`
    : source;
  return `__modules[${JSON.stringify(id)}] = function (module, exports) {\n${body}\n};`;
}

const RUNTIME = `
// --- inlined by scripts/build-functions.mjs; edit hubspot/functions-src ---
const __modules = {};
const __cache = {};
function __require(id) {
  if (__cache[id]) return __cache[id].exports;
  const module = { exports: {} };
  __cache[id] = module;
  __modules[id](module, module.exports);
  return module.exports;
}
`.trim();

for (const entry of ENTRIES) {
  const modules = collect(entry);
  const entrySource = modules.get(entry);
  const deps = [...modules].filter(([id]) => id !== entry);

  const banner =
    `/* Generated by scripts/build-functions.mjs — do not edit.\n` +
    `   Source: ${SRC}/${entry}${deps.length ? ` (+ ${deps.map(([id]) => id).join(", ")})` : ""} */\n`;

  const out = deps.length
    ? `${banner}\n${RUNTIME}\n\n${deps.map(([id, src]) => wrap(id, src)).join("\n\n")}\n\n${entrySource}`
    : `${banner}\n${entrySource}`;

  writeFileSync(path.join(OUT, entry), out);
  console.log(`build-functions: ${entry} <- ${1 + deps.length} file(s), ${out.length} characters`);
}
